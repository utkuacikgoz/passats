#!/usr/bin/env node
/**
 * Rebuilds the "featured on" band in views/index.html, and the Organization
 * sameAs in its JSON-LD, from config/launches.js.
 *
 * The band is a CSS-only marquee: no script, so nothing for the CSP to hash.
 * It needs each item to appear several times to fill a wide screen and a
 * second identical track to loop without a seam. Writing those copies by hand
 * is how one launch ends up in four places and a new one in three, so they are
 * generated. Only the first copy of each launch is exposed to assistive tech
 * and the keyboard; every repeat is aria-hidden and out of the tab order.
 *
 * Usage: npm run sync:launches   (also run by npm run sync:seo)
 */
const fs = require('fs');
const path = require('path');
const { LAUNCHES } = require('../config/launches');

const INDEX_PATH = path.join(__dirname, '..', 'views', 'index.html');
const START = '<!-- launch-strip:start (generated by npm run sync:launches from config/launches.js) -->';
const END = '<!-- launch-strip:end -->';
// Enough items per track to overrun a wide desktop viewport, whatever the count.
const MIN_ITEMS_PER_TRACK = 6;
// Seconds per item, so the speed reads the same however many launches there are.
const SECONDS_PER_ITEM = 5;

const escapeHtml = s => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function validate(launches) {
  if (!Array.isArray(launches) || launches.length === 0) throw new Error('config/launches.js must list at least one launch');
  const seen = new Set();
  for (const launch of launches) {
    if (!launch.name || !launch.url) throw new Error(`every launch needs a name and a url: ${JSON.stringify(launch)}`);
    if (new URL(launch.url).protocol !== 'https:') throw new Error(`launch url must be https: ${launch.url}`);
    if (seen.has(launch.url)) throw new Error(`duplicate launch url: ${launch.url}`);
    seen.add(launch.url);
  }
}

function item(launch, hidden) {
  const label = escapeHtml(launch.label || 'Featured on');
  const attrs = hidden ? ' tabindex="-1"' : '';
  return `<li${hidden ? ' aria-hidden="true"' : ''}><a class="launch-item" href="${escapeHtml(launch.url)}" target="_blank" rel="noopener noreferrer"${attrs}>${label} <b>${escapeHtml(launch.name)}</b><span class="launch-arrow" aria-hidden="true">&nearr;</span></a></li>`;
}

function buildStrip(launches) {
  const repeats = Math.max(1, Math.ceil(MIN_ITEMS_PER_TRACK / launches.length));
  const perTrack = launches.length * repeats;
  const track = hiddenTrack => {
    const items = [];
    for (let r = 0; r < repeats; r++) {
      for (const launch of launches) items.push(item(launch, hiddenTrack || r > 0));
    }
    return items.map(li => `          ${li}`).join('\n');
  };
  return [
    START,
    '  <section class="launch-strip" aria-labelledby="launch-heading">',
    '    <h2 id="launch-heading" class="sr-only">Where to find PassATS</h2>',
    `    <div class="marquee" style="--marquee-duration: ${perTrack * SECONDS_PER_ITEM}s">`,
    '      <div class="marquee-reel">',
    '        <ul class="marquee-track">',
    track(false),
    '        </ul>',
    '        <ul class="marquee-track" aria-hidden="true">',
    track(true),
    '        </ul>',
    '      </div>',
    '    </div>',
    '  </section>',
    `  ${END}`,
  ].join('\n');
}

function syncSameAs(html, launches) {
  const block = /("sameAs":\s*\[)([\s\S]*?)(\])/;
  if (!block.test(html)) throw new Error('Organization sameAs not found in views/index.html');
  const urls = launches.map(l => `    ${JSON.stringify(l.url)}`).join(',\n');
  // A callback, not a replacement string: a URL containing `$&` or `$1` would
  // otherwise be expanded by String.replace and corrupt the JSON-LD.
  return html.replace(block, (_, open, _old, close) => `${open}\n${urls}\n  ${close}`);
}

function sync(html, launches = LAUNCHES) {
  validate(launches);
  const start = html.indexOf(START);
  const end = html.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error('launch-strip markers not found in views/index.html');
  const before = html.slice(0, start);
  const after = html.slice(end + END.length);
  return syncSameAs(before + buildStrip(launches) + after, launches);
}

if (require.main === module) {
  const html = fs.readFileSync(INDEX_PATH, 'utf8');
  const next = sync(html);
  if (next === html) {
    console.log('Launch strip already current.');
  } else {
    fs.writeFileSync(INDEX_PATH, next);
    console.log(`Launch strip rebuilt for ${LAUNCHES.length} launch(es).`);
  }
}

module.exports = { sync, buildStrip, START, END };
